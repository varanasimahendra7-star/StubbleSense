def get_synthetic_fire_events(
    district: Optional[str] = None,
    state: Optional[str] = None,
    date: Optional[str] = None,
) -> List[FireObservation]:
    """Return filtered deterministic synthetic fire observations."""
    results: List[FireObservation] = []

    for event in SYNTHETIC_FIRE_EVENTS:
        if district and event["district"].lower() != district.lower():
            continue
        if state and event["state"].lower() != state.lower():
            continue
        if date and not event["observed_at"].startswith(date):
            continue

        results.append(FireObservation(**event))

    return results
